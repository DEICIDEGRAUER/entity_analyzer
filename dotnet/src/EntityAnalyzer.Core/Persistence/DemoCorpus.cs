    /// <summary>Записать демо-корпус в каталог (создаётся при необходимости).
    /// Посторонние .txt удаляются — повторный вызов даёт ровно демо-набор.</summary>
    public static string WriteTo(string dir)
    {
        Directory.CreateDirectory(dir);

        // Идемпотентность: чужие файлы (например, после смены набора) выметаем.
        foreach (var stale in Directory.GetFiles(dir, "*.txt"))
            File.Delete(stale);

        foreach (var (name, text) in Entries)
            File.WriteAllText(Path.Combine(dir, name), text, new UTF8Encoding(false));

        return dir;
    }

    /// <summary>Каталог демо-корпуса по умолчанию (%APPDATA%\EntityAnalyzer\demo_corpus).</summary>
    public static string DefaultDir => Path.Combine(
        ProfilePaths.DirectoryPath, "demo_corpus");
