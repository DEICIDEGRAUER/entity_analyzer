namespace EntityAnalyzer.Core.Text;

/// <summary>
/// R1-13: препроцессор текста — преобразование извлечённого документа
/// ДО нормализации и поиска. Реализации обязаны быть чистыми функциями
/// (без побочных эффектов) и не терять содержательные строки.
/// Пользовательские C#-скрипты (Roslyn) подключаются сюда же после
/// согласования зависимости; формат конфигурации менять не придётся.
/// </summary>
public interface ITextPreprocessor
{
    /// <summary>Стабильное имя для конфигурации и подписи кэша.</summary>
    string Name { get; }

    /// <summary>Преобразовать текст документа.</summary>
    string Process(string text, string filePath);
}
